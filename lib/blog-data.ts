const getToc = (sections: string[]) => {
  const toc = sections.map((section, index) => ({
    id: `section-${index + 1}`,
    title: section,
    level: 2
  }));
  toc.push({ id: 'conclusion', title: 'الخلاصة', level: 2 });
  return toc;
};

